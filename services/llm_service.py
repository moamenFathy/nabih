async def run_llm_test():
    console.print(Panel(
        f"[bold cyan]Testing Sovereign Qwen 27B-FP8 & Shuri Persona[/bold cyan]\n"
        f"Endpoint: {settings.QWEN_BASE_URL}\n"
        f"Model: SovereignEG/Qwen3.8-27B-FP8 | Temperature: {settings.LLM_TEMPERATURE}\n"
        "Sending conversational prompt to test Shuri's response in Egyptian Arabic...",
        title="🧠 [bold blue]SOVEREIGN QWEN LLM TEST[/bold blue]",
        border_style="blue",
    ))

    llm = LLMService()
    test_prompt = "عرفيني بنفسك يا شوري وقوليلي هتعملي إيه في مشروعي ده؟"

    console.print(f"👤 [bold cyan]المستخدم:[/bold cyan] {test_prompt}\n")

    session = PipelineTelemetry("llm_brain_test")
    accumulated_text = ""
    ttft_value = 0.0

    with session.profile_step("Qwen 27B Brain", "🧠") as step:
        start = time.perf_counter()
        
        with Live(console=console, refresh_per_second=15) as live:
            async for token, ttft in llm.chat_stream(test_prompt):
                if ttft is not None:
                    ttft_value = ttft
                accumulated_text += token
                
                display = Text()
                display.append("🤖 شوري: ", style="bold magenta")
                display.append(accumulated_text, style="bold white")
                live.update(Panel(display, border_style="magenta", expand=False))

        total_ms = round((time.perf_counter() - start) * 1000, 2)
        words = len(accumulated_text.split())
        step.notes = f"TTFT: {ttft_value:.1f}ms | Total: {total_ms:.1f}ms | Words: {words} | Model: Qwen 27B"

    session.print_telemetry_table(
        user_text=test_prompt,
        shuri_reply=accumulated_text
    )


if __name__ == "__main__":
    asyncio.run(run_llm_test())
