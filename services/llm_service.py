class LLMService:
    """Manages conversational reasoning with hosted Qwen 27B on Sovereign EG."""

    def __init__(
        self,
        base_url: str = settings.QWEN_BASE_URL,
        api_key: str = settings.QWEN_API_KEY,
        model: str = settings.QWEN_MODEL_NAME,
        temperature: float = settings.LLM_TEMPERATURE,
        max_tokens: int = settings.LLM_MAX_TOKENS,
        max_history_turns: int = 10,
    ):
        self.base_url = base_url
        self.api_key = api_key
        # Ensure exact Sovereign model tag if needed
        self.model = "SovereignEG/Qwen3.8-27B-FP8" if "sovereign" in base_url.lower() and not model.startswith("SovereignEG/") else model
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.max_history_turns = max_history_turns

        self._client = AsyncOpenAI(
            base_url=self.base_url,
            api_key=self.api_key,
            timeout=15.0,
        )
        self.conversation_history: List[Dict[str, str]] = []

    def reset_history(self):
        """Clears conversational memory."""
        self.conversation_history.clear()
        logger.debug("[LLM SERVICE] Chat history reset.")

    def _build_messages(self, user_message: str) -> List[Dict[str, str]]:
        """Constructs full message payload with system prompt and sliding history."""
        messages = [{"role": "system", "content": SHURI_SYSTEM_PROMPT}]

        # Keep only the last N turns to avoid context overflow
        trimmed_history = self.conversation_history[-(self.max_history_turns * 2):]
        messages.extend(trimmed_history)
        messages.append({"role": "user", "content": user_message})

        return messages

    async def chat_stream(self, user_message: str) -> AsyncGenerator[Tuple[str, Optional[float]], None]:
        """
        Streams response tokens as they are generated by Sovereign Qwen.
        Yields: (token_str, ttft_ms_on_first_token)
        """
        messages = self._build_messages(user_message)
        start_time = time.perf_counter()
        first_token_time = None
        full_response = []

        try:
            stream = await self._client.chat.completions.create(
                model=self.model,
                messages=messages,
                temperature=self.temperature,
                max_tokens=self.max_tokens,
                stream=True,
            )

            async for chunk in stream:
                delta = chunk.choices[0].delta if chunk.choices else None
                if delta and delta.content:
                    if first_token_time is None:
                        first_token_time = round((time.perf_counter() - start_time) * 1000, 2)
                        ttft = first_token_time
                    else:
                        ttft = None

                    full_response.append(delta.content)
                    yield delta.content, ttft

            # Update conversation history on completion
            complete_text = "".join(full_response).strip()
            self.conversation_history.append({"role": "user", "content": user_message})
            self.conversation_history.append({"role": "assistant", "content": complete_text})

        except Exception as ex:
            logger.error(f"[LLM SERVICE] Sovereign Qwen streaming error: {ex}")
            raise ex

    async def generate_response(self, user_message: str) -> Tuple[str, float, float]:
        """
        Convenience method to generate full response and measure TTFT and total latency.
        Returns: (full_text, ttft_ms, total_duration_ms)
        """
        start_time = time.perf_counter()
        accumulated = []
        ttft_recorded = 0.0

        async for token, ttft in self.chat_stream(user_message):
            if ttft is not None:
                ttft_recorded = ttft
            accumulated.append(token)

        total_duration = round((time.perf_counter() - start_time) * 1000, 2)
        return "".join(accumulated).strip(), ttft_recorded, total_duration


